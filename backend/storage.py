"""Project folders: data/projects/<id>/

    source.<ext>     original upload (kept for re-processing)
    track.mp3        audio for AstroDX and the music bar
                     (mp3 uploads copied untouched, others converted once;
                     the original upload is not kept)
    analysis.wav     mono 22050 Hz decode of track.mp3. A cache only:
                     safe to delete, rebuilt by ensure_analysis_wav()
    peaks.bin        waveform peaks for the music bar
    bg.jpg|bg.png    jacket (uploaded > embedded cover > none)
    project.json     metadata (title, artist, duration, timing...)
"""
from __future__ import annotations

import json
import re
import shutil
import uuid
from pathlib import Path
from backend import config
from backend.audio import loader, waveform
from backend.models.project import Project

GENERIC_STEMS = {"track", "audio", "music", "song", "bgm", "source"}

def project_dir(pid: str) -> Path:
    # ids are generated by us; still refuse anything path-like
    if not pid or any(c in pid for c in "/\\.") or len(pid) > 40:
        raise ValueError(f"bad project id {pid!r}")
    return config.PROJECTS_DIR / pid


def save_project(p: Project) -> None:
    d = project_dir(p.id)
    (d / "project.json").write_text(p.model_dump_json(indent=2), encoding="utf-8")


def load_project(pid: str) -> Project:
    f = project_dir(pid) / "project.json"
    if not f.is_file():
        raise FileNotFoundError(f"no project {pid}")
    return Project.model_validate_json(f.read_text(encoding="utf-8"))


def list_projects() -> list[Project]:
    if not config.PROJECTS_DIR.is_dir():
        return []
    out = []
    for d in sorted(config.PROJECTS_DIR.iterdir()):
        try:
            out.append(load_project(d.name))
        except Exception:
            continue
    return sorted(out, key=lambda p: p.created, reverse=True)


def guess_title_artist(audio_path: Path, original_name: str) -> loader.Tags:
    """Fallback when the file has no tags.
    1. a maidata.txt next to the audio (re-charting an existing level)
    2. the parent folder name, if the file is just "track.mp3" etc.
    3. the filename itself
    """
    audio_path = Path(audio_path)
    md = audio_path.parent / "maidata.txt"
    if md.is_file():
        found = {}
        for line in md.read_text(encoding="utf-8", errors="replace").splitlines():
            m = re.match(r"&(title|artist)=(.*)", line.strip())
            if m and m.group(2).strip():
                found.setdefault(m.group(1), m.group(2).strip())
        if found.get("title"):
            return loader.Tags(found["title"], found.get("artist", ""))
    stem = Path(original_name).stem
    if stem.lower() in GENERIC_STEMS and audio_path.parent.name:
        return loader.Tags(audio_path.parent.name, "")
    return loader.Tags(stem, "")


def create_project(audio_path: Path, original_name: str | None = None,
                   jacket_path: Path | None = None) -> Project:
    audio_path = Path(audio_path)
    name = original_name or audio_path.name
    ext = Path(name).suffix.lower()
    if ext not in config.AUDIO_EXTS:
        raise ValueError(f"unsupported audio type {ext!r}")
    if jacket_path is not None and Path(jacket_path).suffix.lower() not in config.IMAGE_EXTS:
        raise ValueError("unsupported jacket image type")

    pid = uuid.uuid4().hex[:12]
    d = project_dir(pid)
    d.mkdir(parents=True)
    try:
        # read tags/cover straight from the upload; it isn't copied into the project
        src = audio_path
        loader.make_track_mp3(src, d / "track.mp3")
        loader.make_analysis_wav(d / "track.mp3", d / "analysis.wav")
        samples, sr = loader.read_wav(d / "analysis.wav")
        if len(samples) < sr:  # < 1 s
            raise loader.AudioError("audio is shorter than 1 second")

        waveform.write_peaks(waveform.compute_peaks(samples, config.PEAKS_SPP), d / "peaks.bin")

        tags = loader.read_tags(src)
        guess = guess_title_artist(audio_path, name)
        jacket = loader.save_jacket(Path(jacket_path) if jacket_path else None,
                                    loader.extract_cover(src), d)
        p = Project(
            id=pid,
            source_name=name,
            title=tags.title or guess.title,
            artist=tags.artist or guess.artist,
            duration=round(len(samples) / sr, 3),
            jacket=jacket,
        )
        save_project(p)
        # small sidecar the frontend needs to draw peaks.bin
        (d / "peaks.json").write_text(json.dumps({
            "sample_rate": sr, "spp": config.PEAKS_SPP,
            "count": len(samples) // config.PEAKS_SPP,
            "first_sound": round(waveform.first_sound_time(samples, sr), 3),
        }), encoding="utf-8")
        return p
    except Exception:
        shutil.rmtree(d, ignore_errors=True)
        raise


def ensure_analysis_wav(pid: str) -> Path:
    """Return analysis.wav for a project, rebuilding it from track.mp3 if it
    was deleted."""
    d = project_dir(pid)
    wav = d / "analysis.wav"
    if not wav.is_file():
        loader.make_analysis_wav(d / "track.mp3", wav)
    return wav


def delete_project(pid: str) -> None:
    shutil.rmtree(project_dir(pid), ignore_errors=True)