"""Turn data/corpus_stats.json (tools/corpus_stats.py) into the generator's
per-level numbers: backend/generator/priors.py. Only medians and shares go
in, no chart content.

    python -m tools.make_priors [path/to/corpus_stats.json]

Levels with very few charts (15) are extrapolated from 14 and 14+.
"""
from __future__ import annotations

import json
import math
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "data" / "corpus_stats.json"
OUT = ROOT / "backend" / "generator" / "priors.py"
LEVELS = ["10", "10+", "11", "11+", "12", "12+", "13", "13+", "14", "14+", "15"]
MIN_CHARTS = 20                     # fewer than this: extrapolate instead


def med(rows, key):
    v = [r[key] for r in rows if r.get(key) is not None]
    return float(np.median(v)) if v else None


def main() -> None:
    src = Path(sys.argv[1]) if len(sys.argv) > 1 else SRC
    d = json.loads(src.read_text(encoding="utf-8"))
    rows, L = d["rows"], d["levels"]
    table, dists = {}, {}
    for lv in LEVELS:
        rs = [r for r in rows if r["level"] == lv]
        if len(rs) < MIN_CHARTS:
            continue
        dx = [r for r in rs if r.get("dx")]
        table[lv] = {
            "charts": len(rs),
            "nps": med(rs, "nps"), "peak_nps": med(rs, "peak_nps"),
            "each_pct": med(rs, "each_pct"), "hold_pct": med(rs, "hold_pct"),
            "touch_pct": med(dx, "touch_pct") or 0.0,          # DX charts (we write DX)
            "break_pct": med(rs, "break_pct"), "slides_per_min": med(rs, "slide_pm"),
            "longest_stream": med(rs, "longest_stream"), "bursts_pm": med(rs, "bursts_pm") or 0.0,
        }
        dists[lv] = {k: L[lv][k] for k in ("steps", "each_dist", "slide_beats", "slide_shape")}

    # extrapolate missing top levels from the last two (log-linear for densities)
    have = [lv for lv in LEVELS if lv in table]
    for lv in LEVELS:
        if lv in table:
            continue
        a, b = table[have[-2]], table[have[-1]]
        step = LEVELS.index(lv) - LEVELS.index(have[-1])
        t = {"charts": 0}
        for k in a:
            if k == "charts":
                continue
            if k in ("nps", "peak_nps", "longest_stream", "bursts_pm") and a[k] > 0 and b[k] > 0:
                t[k] = b[k] * (b[k] / a[k]) ** step
            else:
                t[k] = max(0.0, b[k] + (b[k] - a[k]) * step)
        table[lv] = t
        dists[lv] = dists[have[-1]]

    def r(x):
        return round(x, 3) if isinstance(x, float) else x

    lines = ['"""Per-level numbers measured on the community chart collection',
             f"({d['songs']} songs, {d['charts']} charts of level 10+; utage and excluded folders",
             "left out). Generated by tools/make_priors.py from data/corpus_stats.json:",
             "don't edit by hand, re-run that instead.",
             "",
             "LEVEL_TABLE: medians per level (touch: DX charts only; charts == 0: extrapolated).",
             "STEPS: next button - previous (-4..3) for single notes, by gap: fast < 0.13 s,",
             "mid < 0.2 s, slow < 0.6 s. EACH_DIST: ring distance between EACH buttons.",
             "SLIDE_BEATS: slide travel in beats. SLIDE_SHAPE: '-d' straight over d buttons,",
             "'arcK' curve passing K buttons, other simai shapes as written.",
             '"""', "",
             "LEVEL_TABLE = {"]
    for lv in LEVELS:
        lines.append(f"    {lv!r}: {{" + ", ".join(f"{k!r}: {r(v)}" for k, v in table[lv].items()) + "},")
    lines.append("}")
    for name, key in (("STEPS", "steps"), ("EACH_DIST", "each_dist"),
                      ("SLIDE_BEATS", "slide_beats"), ("SLIDE_SHAPE", "slide_shape")):
        lines += ["", f"{name} = {{"]
        for lv in LEVELS:
            v = dists[lv][key]
            if key == "steps":
                v = {c: {int(s): p for s, p in v[c].items()} for c in v}
            elif key == "each_dist":
                v = {int(s): p for s, p in v.items() if int(s) > 0}
            elif key == "slide_beats":
                v = {float(s): p for s, p in v.items() if p >= 0.002}
            else:
                v = {s: p for s, p in v.items() if p >= 0.002}
            lines.append(f"    {lv!r}: {v!r},")
        lines.append("}")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT}")
    for lv in LEVELS:
        t = table[lv]
        print(f"{lv:>4} {'(extrapolated)' if not t['charts'] else t['charts']:>14} "
              + " ".join(f"{k}={t[k]:.2f}" for k in t if k != "charts"))


if __name__ == "__main__":
    main()
